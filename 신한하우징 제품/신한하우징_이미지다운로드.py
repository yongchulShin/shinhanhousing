def sanitize_filename(name):
    """Remove/replace characters not allowed in filenames."""
    name = re.sub(r'[<>:"/\\|?*]', '_', name)
    name = name.strip('. ')
    return name[:100] if len(name) > 100 else name


_debug_saved = False  # DEBUG 모드에서 최초 1회만 저장

def fetch_image_url(session, no):
    """Fetch product detail page and extract the main image URL."""
    global _debug_saved
    url = f'http://shinhanhousing.co.kr/bbs/zboard.php?id=product&no={no}'
    try:
        resp = session.get(url, timeout=TIMEOUT)
        if resp.status_code != 200:
            print(f'  HTTP {resp.status_code} (서버가 접근을 차단함)', end=' ')
            return None
        # gzip 압축 자동 해제 (서버가 Content-Encoding 헤더를 빠뜨린 경우 대비)
        raw = resp.content
        if raw[:2] == b'\x1f\x8b':
            try:
                raw = gzip.decompress(raw)
            except Exception:
                pass
        html = raw.decode('euc-kr', errors='replace')

        # DEBUG: 첫 번째 요청의 응답을 파일로 저장
        if DEBUG and not _debug_saved:
            debug_path = Path(OUTPUT_DIR) / 'debug_response.txt'
            debug_path.parent.mkdir(parents=True, exist_ok=True)
            with open(debug_path, 'w', encoding='utf-8') as f:
                f.write(f'URL: {url}\n')
                f.write(f'Status: {resp.status_code}\n')
                f.write(f'Headers: {dict(resp.headers)}\n\n')
                f.write(html)
            print(f'\n  [DEBUG] 응답 저장됨: {debug_path}', end=' ')
            _debug_saved = True

        # Find first product image
        match = re.search(r'src="(data/product/[^"]+\.(?:jpg|jpeg|gif|png))"', html, re.IGNORECASE)
        if match:
            img_path = match.group(1)
            return f'http://shinhanhousing.co.kr/bbs/{img_path}'
    except Exception as e:
        print(f'  ERROR no={no}: {e}', end=' ')
    return None


def download_image(session, img_url, save_path):
    """Download image and save to path."""
    for attempt in range(MAX_RETRIES):
        try:
            resp = session.get(img_url, timeout=TIMEOUT, stream=True)
            if resp.status_code == 200:
                save_path.parent.mkdir(parents=True, exist_ok=True)
                with open(save_path, 'wb') as f:
                    for chunk in resp.iter_content(8192):
                        f.write(chunk)
                return True
            else:
                print(f'  HTTP {resp.status_code} for {img_url}')
        except Exception as e:
            print(f'  Attempt {attempt+1} failed: {e}')
            time.sleep(1)
    return False


def main():
    session = requests.Session()
    session.headers.update(HEADERS)

    # 홈페이지 먼저 방문해서 쿠키 획득 (서버 인증 우회)
    print("홈페이지 접속 중 (쿠키 초기화)...")
    try:
        session.get('http://shinhanhousing.co.kr/', timeout=TIMEOUT)
        session.get('http://shinhanhousing.co.kr/bbs/zboard.php?id=product', timeout=TIMEOUT)
    except Exception as e:
        print(f"  경고: 홈페이지 접속 실패 ({e})")

    # 브라우저 PHPSESSID 수동 설정 (위에서 PHPSESSID 값을 직접 입력한 경우)
    if PHPSESSID:
        session.cookies.set('PHPSESSID', PHPSESSID, domain='shinhanhousing.co.kr')
        print(f"PHPSESSID 쿠키 적용됨: {PHPSESSID[:8]}...")
    else:
        # 쿠키 상태 확인
        cookies = {c.name: c.value for c in session.cookies}
        if 'PHPSESSID' in cookies:
            print(f"자동 획득된 PHPSESSID: {cookies['PHPSESSID'][:8]}...")
        else:
            print("★ 주의: PHPSESSID 쿠키를 획득하지 못했습니다.")
            print("  → 위에서 PHPSESSID 값을 직접 입력하면 더 안정적으로 작동합니다.")
            print("  → Chrome F12 → Application → Cookies → shinhanhousing.co.kr → PHPSESSID")

    output_dir = Path(OUTPUT_DIR)
    output_dir.mkdir(exist_ok=True)

    total = len(PRODUCTS)
    success = 0
    fail = 0
    skip = 0
    failed_products = []

    print(f"\n신한하우징 제품 이미지 다운로드 시작")
    print(f"총 {total}개 제품 | 저장 위치: {output_dir.absolute()}")
    print("-" * 60)

    for i, (no, title, ptype, cat) in enumerate(PRODUCTS, 1):
        # Build save path
        safe_title = sanitize_filename(title)
        folder = output_dir / ptype / cat

        # Skip if already downloaded
        existing = list(folder.glob(f"{safe_title}.*"))
        if existing:
            skip += 1
            continue

        print(f"[{i}/{total}] {ptype}/{cat}/{safe_title}", end=' ... ')

        # Get image URL from detail page
        img_url = fetch_image_url(session, no)
        if not img_url:
            print(f"SKIP (no image found)")
            failed_products.append((no, title, ptype, cat, 'no_image'))
            fail += 1
            time.sleep(DELAY)
            continue

        # Determine file extension
        ext = img_url.rsplit('.', 1)[-1].lower()
        if ext not in ('jpg', 'jpeg', 'gif', 'png'):
            ext = 'jpg'
        save_path = folder / f"{safe_title}.{ext}"

        # Download
        if download_image(session, img_url, save_path):
            size_kb = save_path.stat().st_size // 1024
            print(f"OK ({size_kb}KB)")
            success += 1
        else:
            print(f"FAIL")
            failed_products.append((no, title, ptype, cat, 'download_fail'))
            fail += 1

        time.sleep(DELAY)

        # Progress report every 100 products
        if i % 100 == 0:
            print(f"\n--- 진행: {i}/{total} | 성공: {success} | 실패: {fail} | 스킵: {skip} ---\n")

    print("\n" + "=" * 60)
    print(f"완료! 성공: {success} | 실패: {fail} | 스킵(기존): {skip}")

    if failed_products:
        fail_log = output_dir / 'failed_downloads.txt'
        with open(fail_log, 'w', encoding='utf-8') as f:
            for item in failed_products:
                f.write('|'.join(str(x) for x in item) + '\n')
        print(f"실패 목록: {fail_log}")


if __name__ == '__main__':
    main()